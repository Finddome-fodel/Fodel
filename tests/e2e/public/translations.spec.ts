/**
 * The nine languages as a whole: every page has its counterpart in every
 * language and each counterpart points back (hreflang), no page shows another
 * language's wording, legal pages carry the courtesy-translation note, and
 * the 404 speaks the language of the URL.
 */
import { test, expect } from '../support/fixtures';
import { LOCALES, LOCALE_META, path as routePath, type Locale, type RouteKey } from '../../../src/i18n/ui';

const KEYS: RouteKey[] = [
  'home', 'submitAd', 'contact', 'searchRequest', 'priceList', 'sellers', 'buyers', 'about', 'faq', 'valuation',
  'services', 'agricultural', 'photoGuide', 'buyingGuide', 'emigration', 'privacy', 'terms', 'cookies', 'imprint', 'accessibility',
];
const abs = (p: string) => `https://finddome.com${p}`;

test('hreflang: every page lists all nine languages and every counterpart lists it back', async ({ request }) => {
  test.setTimeout(240_000);
  const problems: string[] = [];
  for (const key of KEYS) {
    const alternates = new Map<Locale, Map<string, string>>();
    for (const locale of LOCALES) {
      const response = await request.get(routePath(locale, key));
      if (response.status() !== 200) {
        problems.push(`${routePath(locale, key)} answers ${response.status()}`);
        continue;
      }
      const html = await response.text();
      const found = new Map<string, string>();
      for (const m of html.matchAll(/<link rel="alternate" hreflang="([^"]+)" href="([^"]+)"/g)) found.set(m[1], m[2]);
      alternates.set(locale, found);
      for (const other of LOCALES) {
        if (found.get(LOCALE_META[other].hreflang) !== abs(routePath(other, key))) {
          problems.push(`${routePath(locale, key)}: hreflang ${other} is ${found.get(LOCALE_META[other].hreflang)}`);
        }
      }
      if (!found.get('x-default')) problems.push(`${routePath(locale, key)}: no x-default`);
      const canonical = html.match(/<link rel="canonical" href="([^"]+)"/)?.[1];
      if (canonical !== abs(routePath(locale, key))) problems.push(`${routePath(locale, key)}: canonical is ${canonical}`);
    }
  }
  expect(problems).toEqual([]);
});

test('the sitemap lists every language (static build only)', async ({ request }) => {
  const index = await request.get('/sitemap-index.xml');
  test.skip(index.status() !== 200, 'the sitemap is generated by the build, not by the dev server');
  const urls = [...(await index.text()).matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]);
  let all = '';
  for (const url of urls) all += await (await request.get(new URL(url).pathname)).text();
  for (const locale of LOCALES) expect(all).toContain(abs(routePath(locale, 'home')));
});

/**
 * Words that give another language away. A page in one language must not show
 * them outside an element that declares its own `lang` (a quoted Dutch or
 * Hungarian original, a language name in the switcher).
 */
const DUTCH = /(?<![\p{L}])(het|een|voor|niet|ook|uw|wij|naar|geen|worden|deze|bent|kunt|onze|woning)(?![\p{L}])/iu;
const HUNGARIAN = /[őűŐŰ]|(?<![\p{L}])(és|hogy|vagy|nincs|egy|ingatlan|hirdetés|kérjük)(?![\p{L}])/iu;

for (const locale of ['en', 'de', 'fr', 'es', 'pl', 'ro', 'sk', 'it', 'pt', 'el', 'cs', 'sl', 'sv', 'da', 'no', 'fi', 'et', 'lv', 'lt'] as const) {
  test(`${locale}: no Dutch or Hungarian wording is left on the static pages`, async ({ page }) => {
    test.setTimeout(240_000);
    const leftovers: string[] = [];
    for (const key of KEYS) {
      await page.goto(routePath(locale, key));
      const text = await page.evaluate((own) => {
        const clone = document.body.cloneNode(true) as HTMLElement;
        clone.querySelectorAll('script, style, noscript, svg').forEach((e) => e.remove());
        clone.querySelectorAll('[lang]').forEach((e) => {
          const lang = e.getAttribute('lang') ?? '';
          if (lang && !lang.startsWith(own)) e.remove();
        });
        return clone.innerText;
      }, locale);
      for (const [name, re] of [['Dutch', DUTCH], ['Hungarian', HUNGARIAN]] as const) {
        const hit = text.match(re);
        if (hit) leftovers.push(`${routePath(locale, key)}: ${name} "${hit[0]}" in "${text.slice(Math.max(0, hit.index! - 40), hit.index! + 50).replace(/\s+/g, ' ')}"`);
      }
    }
    expect(leftovers).toEqual([]);
  });
}

for (const locale of ['en', 'de', 'fr', 'es', 'pl', 'ro', 'sk', 'it', 'pt', 'el', 'cs', 'sl', 'sv', 'da', 'no', 'fi', 'et', 'lv', 'lt'] as const) {
  test(`${locale}: the legal pages say they are a courtesy translation`, async ({ page }) => {
    const needle = {
      en: /translation for convenience/i, de: /Übersetzung/, fr: /traduction/i,
      es: /traducción/i, pl: /tłumaczeni/i, ro: /traducere/i, sk: /preklad/i,
      it: /traduzione/i, pt: /tradução/i, el: /μετάφραση/i, cs: /překlad/i, sl: /prevod/i, sv: /översättning/i,
      da: /oversættelse/i, no: /oversettelse/i, fi: /käännös/i, et: /tõlge/i, lv: /tulkojums/i, lt: /vertimas/i,
    }[locale];
    for (const key of ['privacy', 'terms', 'cookies', 'imprint'] as const) {
      await page.goto(routePath(locale, key));
      await expect(page.locator('main')).toContainText(needle);
    }
  });
}

test('an unknown page answers 404 in the language of its URL', async ({ request }) => {
  const heading: Record<Locale, RegExp> = {
    hu: /nem található|404/i, nl: /niet gevonden|404/i, en: /not found|404/i, de: /nicht gefunden|404/i, fr: /introuvable|404/i,
    es: /no encontrada|404/i, pl: /nie znaleziono|404/i, ro: /nu a fost găsită|404/i, sk: /sa nenašla|404/i,
    it: /non trovata|404/i, pt: /não encontrada|404/i, el: /δεν βρέθηκε|404/i, cs: /nenalezena|404/i, sl: /ni bila najdena|404/i,
    sv: /hittades inte|404/i, da: /blev ikke fundet|404/i, no: /fant ikke|404/i, fi: /ei löytynyt|404/i, et: /ei leitud|404/i,
    lv: /nav atrasta|404/i, lt: /nerastas|404/i,
  };
  for (const locale of LOCALES) {
    const response = await request.get(`/${locale}/this-page-does-not-exist/`);
    expect(response.status()).toBe(404);
    const html = await response.text();
    expect(html).toMatch(new RegExp(`<html[^>]*lang="${LOCALE_META[locale].htmlLang}"`));
    expect(html).toMatch(heading[locale]);
  }
});

test('prices and areas are written the local way', async ({ page }) => {
  await page.goto(routePath('de', 'priceList'));
  await expect(page.locator('main')).toContainText(/\d\s?€/);
  await page.goto(routePath('en', 'priceList'));
  await expect(page.locator('main')).toContainText(/€\s?\d/);
  await page.goto(routePath('fr', 'priceList'));
  await expect(page.locator('main')).toContainText(/\d\s€/);
});
