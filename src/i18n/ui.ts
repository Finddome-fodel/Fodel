/* Spanish, Polish, Romanian and Slovak: the formal register that matches the
   French "vous" (usted, Państwo, dumneavoastră, vykanie). Plurals follow
   Intl.PluralRules; Romanian adds "de" from 20 upwards. */
const pluralOf = (tag: string, n: number, one: string, few: string, many = few) => {
  const cat = new Intl.PluralRules(tag).select(n);
  return `${n} ${cat === 'one' ? one : cat === 'few' ? few : many}`;
};

