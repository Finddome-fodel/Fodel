/** A value written out once per language. The compiler refuses a missing one. */
export type L10n<T = string> = Record<Locale, T>;

/** Pick the visitor's language from a complete set of translations. */
export function pick<T>(locale: Locale, values: L10n<T>): T {
  return values[locale];
}

/**
 * A positional picker for short inline strings:
 *
 *   const x = localizer(locale);
 *   x('Ingatlanok', 'Ons aanbod', 'Properties', 'Immobilien', 'Biens', 'Inmuebles', 'Nieruchomości', 'Proprietăți', 'Nehnuteľnosti', 'Immobili', 'Imóveis', 'Ακίνητα', 'Nemovitosti', 'Nepremičnine', 'Fastigheter', 'Ejendomme', 'Eiendommer', 'Kiinteistöt', 'Kinnisvara', 'Īpašumi', 'Nekilnojamasis turtas')
 *
 * The order is always hu, nl, en, de, fr, es, pl, ro, sk, it, pt, el, cs, sl, sv, da, no, fi, et, lv, lt, and all twenty-one arguments are required,
 * so a twenty-second language or a forgotten translation is a compile error, never a
 * silent fall-through to Dutch. Longer texts belong in a data file instead.
 */
export function localizer(locale: Locale) {
  const index = LOCALES.indexOf(locale);
  return (
    hu: string, nl: string, en: string, de: string, fr: string, es: string, pl: string, ro: string, sk: string, it: string, pt: string, el: string, cs: string, sl: string, sv: string, da: string, no: string, fi: string, et: string, lv: string, lt: string,
  ): string => [hu, nl, en, de, fr, es, pl, ro, sk, it, pt, el, cs, sl, sv, da, no, fi, et, lv, lt][index];
}

