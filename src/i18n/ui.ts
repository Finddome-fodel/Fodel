/* Spanish, Polish, Romanian and Slovak: the formal register that matches the
   French "vous" (usted, Państwo, dumneavoastră, vykanie). Plurals follow
   Intl.PluralRules; Romanian adds "de" from 20 upwards; Slovenian has a
   dual (`two`). */
const pluralOf = (tag: string, n: number, one: string, few: string, many = few, two = few) => {
  const form = pluralForm(tag, n);
  return `${n} ${form === 'one' ? one : form === 'two' ? two : form === 'few' ? few : many}`;
};

