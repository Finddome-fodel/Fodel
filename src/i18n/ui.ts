export const LOCALES = ['hu', 'nl', 'en', 'de', 'fr', 'es', 'pl', 'ro', 'sk'] as const;
export type Locale = (typeof LOCALES)[number];

/** Every market FODEL sells in. Kept as an alias: all nine now have a full site. */
export const PLANNED_LOCALES = LOCALES;
export type PlannedLocale = Locale;

/** A value written out once per language. The compiler refuses a missing one. */
export type L10n<T = string> = Record<Locale, T>;

/** Pick the visitor's language from a complete set of translations. */
export function pick<T>(locale: Locale, values: L10n<T>): T {
  return values[locale];
}

/**
 * A positional picker for short inline strings:
 *
 *   const x = localizer(locale);
 *   x('Ingatlanok', 'Ons aanbod', 'Properties', 'Immobilien', 'Biens', 'Inmuebles', 'Nieruchomości', 'Proprietăți', 'Nehnuteľnosti')
 *
 * The order is always hu, nl, en, de, fr, es, pl, ro, sk, and all nine arguments are required,
 * so a tenth language or a forgotten translation is a compile error, never a
 * silent fall-through to Dutch. Longer texts belong in a data file instead.
 */
export function localizer(locale: Locale) {
  const index = LOCALES.indexOf(locale);
  return (hu: string, nl: string, en: string, de: string, fr: string, es: string, pl: string, ro: string, sk: string): string =>
    [hu, nl, en, de, fr, es, pl, ro, sk][index];
}

